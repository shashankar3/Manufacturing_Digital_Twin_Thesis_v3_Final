class PredictionValidator:
    """
    Compares the Digital Twin predictions against
    the actual future events generated by System A.

    During the validation phase, learning is frozen.
    The validator records:

        1. Predicted future trajectory.
        2. Actual future events.

    These are later compared to evaluate the
    prediction accuracy of the Digital Twin.
    """

    def __init__(self):

        # -----------------------------------------
        # Stored predictions
        # -----------------------------------------

        self.predictions = []

        # -----------------------------------------
        # Actual events observed after freezing
        # -----------------------------------------

        self.actual_events = []

    # =====================================================
    # Prediction Recording
    # =====================================================

    def store_predictions(
        self,
        predictions,
    ):
        """
        Store the predicted future trajectory.
        """

        self.predictions = predictions

    # =====================================================
    # Actual Event Recording
    # =====================================================

    def record_event(
        self,
        event,
    ):
        """
        Record one actual event occurring after
        the Digital Twin has been frozen.
        """

        self.actual_events.append(event)

    # =====================================================
    # Debug Output
    # =====================================================

    def print_summary(self):

        print("\n")
        print("=" * 60)
        print("Prediction Validation")
        print("=" * 60)

        print(f"Predicted States : {len(self.predictions)}")
        print(f"Observed Events  : {len(self.actual_events)}")

        print("\nPredictions")

        for prediction in self.predictions:

            print(prediction)

        print("\nObserved Events")

        for event in self.actual_events:

            print(event)